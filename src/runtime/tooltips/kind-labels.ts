/** Human label for a class key, e.g. "bus_stop" → "Bushaltestelle". */
export function kindLabel(key: unknown, lang: string): string {
  if (typeof key !== 'string' || !key) return '';
  const label = LABELS[key.toLowerCase()];
  if (label) return lang === 'de' ? label[0] : label[1];
  const text = key.replace(/_/g, ' ');
  return text.charAt(0).toUpperCase() + text.slice(1);
}
